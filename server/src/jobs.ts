/** SMS per user and day (SMS_MAX_PER_DAY) – cost and abuse protection; also counts SMS sent again by hand. */
const smsToday = new Map<string, { day: string; count: number }>();
export function takeSmsQuota(owner: string): boolean {
  const day = new Date().toISOString().slice(0, 10);
  const used = smsToday.get(owner);
  const count = used?.day === day ? used.count : 0;
  if (count >= config.smsMaxPerDay) return false;
  smsToday.set(owner, { day, count: count + 1 });
  return true;
}

/**
 * The password of one step by SMS: read from its Vaultwarden Send right before sending (it is stored nowhere else)
 * and sent via seven.io. The Send stays until the links expire, so the sender can send the password again.
 * If the SMS cannot be sent (seven.io error, daily limit), the password goes out **no other way**: the sender gets a
 * note without password and sends it again in CloudShare ("Kennwort" at the link) – by SMS or mail.
 */
async function sendStepBySms(
  job: PasswordJob,
  part: SeparatePart,
  to: string,
  t: Templates,
  tokens: string[],
  graphToken: string,
  sender: string | null | undefined,
  subject: string,
  log: Pick<FastifyBaseLogger, "info" | "warn">,
  /** Language of the sender's add-in – the note about a failed SMS comes in it. */
  senderLanguage?: string,
) {
  try {
    if (!smsEnabled()) throw new Error(translate("server.smsNotConfigured"));
    // SMS_ALLOWED_COUNTRIES / _NUMBERS / SMS_BLOCKED_NUMBERS may have changed since the number was entered.
    const problem = smsNumberProblem(to);
    if (problem) throw new Error(problem);
    if (!takeSmsQuota(job.owner)) throw new Error(translate("server.smsDailyLimit", { max: config.smsMaxPerDay }));
    const password = await readSendPassword(part.sendId!);
    // In the step's language, like its password mail.
    const text = inRecipientLanguage(part.language, () =>
      render(t.sms_template, { password, sender_name: job.senderName ?? "", files: smsFiles(partFiles(part)) }));
    const messageId = await sendSms(to, text);
    await recordDelivery(tokens, { owner: job.owner, channel: "sms", to: maskPhone(to), at: Date.now(), messageId, status: "submitted" });
    log.info({ user: job.ownerUpn, to: maskPhone(to), messageId }, "Password SMS sent");
  } catch (err) {
    log.warn({ err, user: job.ownerUpn, to: maskPhone(to) }, "Password SMS failed – note to the sender, no password sent");
    await recordDelivery(tokens, { owner: job.owner, channel: "sms", to: maskPhone(to), at: Date.now(), status: "failed" });
    // The note to the sender in the language of their add-in.
    const { html, noteSubject } = inSenderLanguage(senderLanguage, () => ({
      html: smsProblemMailHtml({ fileNames: partFiles(part), subject, to: maskPhone(to), reason: (err as Error).message }),
      noteSubject: translate("mail.smsFailedSubject", {
        subject: subject || translate("mail.files", { count: partFiles(part).length, name: partFiles(part)[0] }),
      }),
    }));
    // A failed note must not fail the step – that would retry the SMS on every pass of the watcher.
    await sendMail(graphToken, { to: [sender ?? job.ownerUpn], cc: [], bcc: [] }, noteSubject, html, sender)
      .catch((mailErr) => log.warn({ err: mailErr, user: job.ownerUpn }, "Note about the failed SMS not sent"));
  }
}

/** One pass of the watcher over all jobs (exported for tests; normally driven by startJobWatcher). */
export async function checkJobs(log: Pick<FastifyBaseLogger, "info" | "warn">) {
  const now = Date.now();
  for (const [id, job] of jobs) {
    if (job.expiresAt < now) {
      // A draft with links that was never sent (discarded): its links never left the mailbox – revoke them.
      if (unsentHandler && neverSent(job)) {
        const sendIds = [job.sendId, ...(job.separate ?? []).map((part) => part.sendId)].filter((s): s is string => Boolean(s));
        const tokens = jobTokens(job);
        try {
          if (tokens.length || sendIds.length) {
            await unsentHandler({ owner: job.owner, ownerUpn: job.ownerUpn, tokens, sendIds: [...new Set(sendIds)] }, log);
          }
        } catch (err) {
          log.warn({ err, user: job.ownerUpn, jobId: id }, "Links of a mail never sent not revoked, retrying later");
          job.expiresAt = now + UNSENT_RETRY;
          jobs.save(id);
          continue;
        }
      }
      jobs.delete(id);
      continue;
    }
    const armed = job.armed;
    if (job.dispatched || !armed) continue;

    if (now - armed.armedAt > ARM_WINDOW || armed.tokenExpiresAt < now) {
      // The mail was not sent (prompt cancelled, sending failed, draft discarded) – keep the job open.
      job.armed = undefined;
      jobs.save(id);
      log.info({ user: job.ownerUpn, jobId: id }, "Send not observed in Sent Items, job disarmed");
      continue;
    }

    try {
      // Small margin for clock differences between this server and Exchange.
      const since = armed.armedAt - 2 * MINUTE;
      // Exchange Online saves the copy in the sender's own "Sent Items" by default; depending on mailbox and client
      // settings it may (also or only) land in the shared mailbox's "Sent Items".
      let sent = await findSentMessage(armed.graphToken, id, since);
      // The pane can open only mails of the user's own mailbox ("Verlauf").
      const ownCopy = Boolean(sent);
      if (!sent && armed.mailbox) {
        sent = await findSentMessage(armed.graphToken, id, since, armed.mailbox).catch((err) => {
          log.warn({ err, user: job.ownerUpn, mailbox: armed.mailbox }, "Shared mailbox not readable");
          return null;
        });
      }
      if (!sent) continue;
      const message = sent; // stays non-null inside the closures below
      // "Zustellnachweis": the mail as Exchange sent it (Message-ID, sender, recipients) – in the case of its links.
      recordMailSent([...jobTokens(job), ...(job.noticeShares ?? []).map((s) => s.token)], {
        subject: message.subject,
        messageId: message.messageId,
        from: message.from,
        ...message.recipients,
        sentAt: message.sentAt,
      });
      // Same sender as the main mail – for a shared mailbox the password mail is sent as / on behalf of it.
      // "Kennwort an andere Adresse": only that address gets the password, not the recipients of the mail.
      const recipients = job.passwordTo ? { to: [job.passwordTo], cc: [], bcc: [] } : message.recipients;
      const sender = message.from ?? armed.mailbox;
      /**
       * Download confirmation (file links) and upload notification (upload links) for these links, now that subject
       * and recipients of the sent mail are known.
       */
      const watchDownloads = (shares: StepShare[]) =>
        registerNotices(
          shares.filter((s) => !s.message).map((s): [string, Notice] => [
            s.token,
            {
              owner: job.owner,
              ownerUpn: job.ownerUpn,
              notifyTo: message.from ?? job.ownerUpn,
              department: job.department,
              fileName: s.name,
              subject: message.subject,
              recipients: message.recipients.to.concat(message.recipients.cc).join(", "),
              expireDate: s.expireDate,
              registeredAt: Date.now(),
              // The confirmation to the sender in the language of their add-in.
              language: armed.language,
              // "Zustellnachweis": the confirmation names the case.
              proofId: caseOfToken(s.token)?.id,
              ...(s.request ? { kind: "upload" as const, knownFiles: s.knownFiles ?? [] } : {}),
            },
          ]),
        ).catch((err) => log.warn({ err, user: job.ownerUpn }, "Download confirmation could not be registered"));
      /** "Verlauf": subject of the sent mail per link, and its ID to open it (own mailbox only). */
      const rememberMail = (shares: StepShare[], keepUntil: number) =>
        recordSentMail(
          shares.map((s) => s.token),
          {
            owner: job.owner,
            subject: message.subject,
            mailId: ownCopy ? message.id : undefined,
            keepUntil,
            // For the tooltip of the subject: when and to whom (To and Cc as in the mail; Bcc stays hidden).
            sentAt: message.sentAt ? Date.parse(message.sentAt) : Date.now(),
            to: message.recipients.to,
            cc: message.recipients.cc,
          },
        );

      if (job.noPassword) {
        // Links without password: nothing to send, only the download confirmation.
        rememberMail(job.noticeShares ?? [], linksExpireAt(job.noticeShares ?? []));
        await watchDownloads(job.noticeShares ?? []);
      } else if (job.separate?.length) {
        // One password per step: one password mail (or SMS) per step, naming its files. Parts already sent stay
        // sent, so a retry after an error does not send them twice.
        for (const part of job.separate) {
          if (part.dispatched) continue;
          const files = partFiles(part);
          // What the recipients read comes in the step's language ("Sprache für die Empfänger"); notes to the sender
          // (a failed SMS) stay in LANGUAGE.
          const t = inRecipientLanguage(part.language, () => templatesFor({ upn: job.ownerUpn, department: job.department }));
          const mailFor = () =>
            inRecipientLanguage(part.language, () => {
              const customIntro = t.mail_password_intro !== defaultTemplates().mail_password_intro ? t.mail_password_intro : undefined;
              const label = translate("mail.files", { count: files.length, name: files[0] });
              return {
                subject: render(t.mail_password_subject, { files: label, subject: message.subject || files[0], sender_name: job.senderName ?? "" }),
                html: passwordMailHtml({ fileNames: files, sendUrl: part.sendUrl, maxAccessCount: part.maxAccessCount,
                  subject: message.subject, expireDays: config.sendExpireDays, introTemplate: customIntro, senderName: job.senderName,
                  expiresOn: part.sendExpiresAt ? formatDate(part.sendExpiresAt) : undefined, signature: job.signature,
                  trackingId: caseOfToken(part.shares?.[0]?.token ?? "")?.id }),
              };
            });
          const tokens = (part.shares ?? []).map((s) => s.token);
          const ways = partDeliveries(job, part);
          // "Zustellnachweis": every link of the step leads through the gateway – the password goes out only after a
          // recipient confirmed their address there (proofPassword.ts), so the mail and the password do not arrive together.
          const deferred = config.deliveryProof && isDeferredStep(part.shares ?? []);
          if (deferred) eventForTokens(tokens, "password.deferred", { ways: ways.map(deliveryKey) });

          // Every way of the step once: password mail to the recipients or another address, SMS to a number. SMS last –
          // "Verlauf" shows the last delivery, and an SMS has a status to follow. A way already sent (before an
          // error in a later one) is not sent again.
          for (const way of [...ways].sort((a, b) => Number(a.channel === "sms") - Number(b.channel === "sms"))) {
            const key = deliveryKey(way);
            if (part.sentWays?.includes(key)) continue;
            if (deferred) continue;
            if (way.channel === "sms") {
              if (part.sendId) await sendStepBySms(job, part, way.to, t, tokens, armed.graphToken, sender, message.subject, log, armed.language);
            } else {
              const to = way.channel === "mail" ? { to: [way.to], cc: [], bcc: [] } : message.recipients;
              const mail = mailFor();
              await sendMail(armed.graphToken, to, mail.subject, mail.html, sender);
              await recordDelivery(tokens, { owner: job.owner, channel: "mail", to: to.to.concat(to.cc).join(", "), at: Date.now() });
            }
            (part.sentWays ??= []).push(key);
            jobs.save(id);
          }
          part.dispatched = true;
          jobs.save(id);
          rememberMail(part.shares ?? [], part.sendKeepUntil ?? linksExpireAt(part.shares ?? []));
          await watchDownloads(part.shares ?? []);
          // The Send stays until the links expire: the sender can see the password and send it again.
          if (part.sendId && tokens.length > 0) {
            await registerPasswordRef({
              owner: job.owner,
              language: part.language,
              senderLanguage: armed.language,
              ownerUpn: job.ownerUpn,
              sendId: part.sendId,
              tokens,
              fileNames: files,
              keepUntil: part.sendKeepUntil ?? linksExpireAt(part.shares ?? []),
              subject: message.subject,
              recipients: message.recipients,
              otherTo: (() => {
                const others = ways.flatMap((w) => (w.channel === "mail" ? [w.to] : []));
                return others.length ? others : undefined;
              })(),
              sms: ways.find((w): w is Extract<Delivery, { channel: "sms" }> => w.channel === "sms")?.to,
              from: sender ?? undefined,
              maxAccessCount: part.maxAccessCount,
              senderName: job.senderName,
              department: job.department,
              ...(deferred
                ? { deferred: true, toRecipients: ways.some((w) => w.channel === "recipients"), signature: job.signature }
                : {}),
            }).catch((err) => log.warn({ err, user: job.ownerUpn }, "Password entry for resending not recorded"));
          }
        }
      } else {
        await sendMail(armed.graphToken, recipients, translate("mail.subjectLegacy", { subject: sent.subject || job.fileNames[0] }),
          passwordMailHtml({ fileNames: job.fileNames, sendUrl: job.sendUrl, maxAccessCount: job.maxAccessCount,
            subject: sent.subject, expireDays: config.sendExpireDays, signature: job.signature }), sender);
      }
      job.dispatched = true;
      job.armed = undefined;
      jobs.save(id);
      log.info({ user: job.ownerUpn, from: sent.from, files: job.fileNames, other: Boolean(job.passwordTo) }, "Password mail sent");
    } catch (err) {
      log.warn({ err, user: job.ownerUpn, jobId: id }, "Password mail check failed, retrying");
    }
  }
}

/** Starts the background check of armed jobs. */
export function startJobWatcher(log: FastifyBaseLogger) {
  let running = false;
  setInterval(async () => {
    if (running) return;
    running = true;
    try {
      await checkJobs(log);
    } catch (err) {
      log.error({ err }, "Job watcher failed");
    } finally {
      running = false;
    }
  }, POLL_INTERVAL).unref();
}
