export interface ArmedSend {
  /** Delegated Graph token (Mail.Read(.Shared) + Mail.Send(.Shared)) obtained when the user pressed "Send". */
  graphToken: string;
  tokenExpiresAt: number;
  armedAt: number;
  /** Shared mailbox in the "From" field (send as / on behalf); its "Sent Items" are searched as well. */
  mailbox?: string;
  /** Language of the sender's add-in when they pressed "Send" – the notes to them (download confirmation, files
   *  received, SMS problems) come in it. */
  language?: string;
}

/**
 * One "Als Link einfügen" step of a mail: its files share one password, one Send and one password mail. Every
 * further step of the same mail gets its own password and its own password mail.
 */
export interface SeparatePart {
  /** ID of the step, generated by the taskpane per click. */
  step?: string;
  fileNames: string[];
  sendUrl: string;
  sendId?: string;
  maxAccessCount: number;
  /** Until when the recipients can open the step's password link (ms) – shown in the password mail; missing in older jobs. */
  sendExpiresAt?: number;
  /** When the Send itself is deleted (ms) – the expiry of the step's links; until then the password can be resent. */
  sendKeepUntil?: number;
  /** Its password mail went out (the others may still be pending after an error). */
  dispatched?: boolean;
  /**
   * The ways the step's password goes out – one per way chosen for one of its links ("Kennwort senden an" is per
   * insertion): a link sent to the recipients and one of the same password by SMS give one password mail and one SMS.
   * Missing (steps from before): the mail's one way (passwordTo / passwordSms of the job).
   */
  deliveries?: Delivery[];
  /** Ways already sent (deliveryKey) – a retry after an error does not send them twice. */
  sentWays?: string[];
  /** The links of the step (share token, file name, last valid day) – for "Verlauf" and download notices. */
  shares?: StepShare[];
  /** Language of the step's password mail and SMS ("Sprache für die Empfänger"); none: LANGUAGE. */
  language?: string;
}

/** One way the password of a step goes out: the recipients of the mail, another address, or an SMS to a number. */
export type Delivery = { channel: "recipients" } | { channel: "mail"; to: string } | { channel: "sms"; to: string };

export const deliveryKey = (d: Delivery) => (d.channel === "recipients" ? "recipients" : `${d.channel}:${d.to.toLowerCase()}`);

/** The ways of a step: its own, or (steps from before) the one way of the whole mail. */
export function partDeliveries(job: Pick<PasswordJob, "passwordTo" | "passwordSms">, part: SeparatePart): Delivery[] {
  if (part.deliveries?.length) return part.deliveries;
  if (job.passwordSms) return [{ channel: "sms", to: job.passwordSms }];
  if (job.passwordTo) return [{ channel: "mail", to: job.passwordTo }];
  return [{ channel: "recipients" }];
}

export interface StepShare {
  token: string;
  name: string;
  expireDate: string;
  /** An upload link ("Anfordern"): watched for received files (UPLOAD_NOTICE) instead of downloads. */
  request?: true;
  /** Files already in the upload folder when the link was created – not reported as received. */
  knownFiles?: string[];
  /** A confidential message (Vaultwarden Send, token "msg-…", history.ts) – not in Nextcloud, no download confirmation. */
  message?: true;
}

/** End of the last day the links are valid (ms) – for steps created before `sendKeepUntil` existed. */
const linksExpireAt = (shares: StepShare[]) =>
  Math.max(0, ...shares.map((s) => Date.parse(`${s.expireDate}T00:00:00Z`) + 86_400_000).filter(Number.isFinite));

/** Parts stored by the short-lived per-file version had a single `fileName`. */
const partFiles = (part: SeparatePart & { fileName?: string }) =>
  part.fileNames ?? (part.fileName ? [part.fileName] : []);

export interface PasswordJob {
  owner: string;
  ownerUpn: string;
  fileNames: string[];
  /** Set for mails with one password per "Als Link einfügen" step; top-level Send fields describe the first step. */
  separate?: SeparatePart[];
  sendUrl: string;
  /** Vaultwarden Send ID – lets the number of accesses change until sending (jobs created before: none). */
  sendId?: string;
  /** Password mail only to this address instead of the mail's recipients ("Kennwort an andere Adresse"). */
  passwordTo?: string;
  /** Password by SMS to this number (E.164) instead of a password mail ("Kennwort per SMS"). */
  passwordSms?: string;
  /** Sender's display name and department (from the profile when arming) – templates and their selection. */
  senderName?: string;
  department?: string;
  /** Sender's signature for the password mail (HTML from signature.ts, fixed when arming). */
  signature?: string;
  /** How often the password link can be opened (jobs created before this field existed: unknown). */
  maxAccessCount?: number;
  /**
   * Links "Ohne Kennwort" with download confirmation: no password, no Send, no password mail – the job only waits for
   * the sent mail (subject, recipients) and then registers the links in `noticeShares` for the confirmation.
   */
  noPassword?: boolean;
  noticeShares?: StepShare[];
  dispatched: boolean;
  /** Seven days after the last link was added; then the job is dropped (see checkJobs). */
  expiresAt: number;
  armed?: ArmedSend;
  /**
   * "Send" was pressed at least once. false: never – if the job expires that way, the mail was never sent (draft
   * discarded) and its links are revoked. Missing in jobs from older versions: unknown, their links are left alone.
   */
  armedOnce?: boolean;
}

/** The links and Sends of a mail that was never sent, for revoking them (see onUnsentExpired). */
export interface UnsentLinks {
  owner: string;
  ownerUpn: string;
  tokens: string[];
  sendIds: string[];
}

const MINUTE = 60_000;
const JOB_TTL = 7 * 24 * 60 * MINUTE;
/** Revoking the links of a mail never sent failed (Nextcloud unreachable): next try after this time. */
const UNSENT_RETRY = 60 * MINUTE;
/** How long after "Send" the watcher looks for the mail in "Sent Items". */
const ARM_WINDOW = 15 * MINUTE;
const POLL_INTERVAL = 20_000;
/** All jobs; `set`/`delete` write their row, a job changed in place is written with `jobs.save(id)`. */
const jobs = new PersistentMap<PasswordJob>("password-jobs");

export const getJob = (id: string) => jobs.get(id);

/** A link was added: the job lives another JOB_TTL from now (a draft being worked on is not "never sent"). */
const touch = (job: PasswordJob) => {
  job.expiresAt = Date.now() + JOB_TTL;
};

/** Never sent: created by this version, "Send" never pressed, nothing dispatched – links with a password only. */
const neverSent = (job: PasswordJob) => job.armedOnce === false && !job.dispatched && !job.noPassword;

/** Share tokens of a job's links (only steps record them; jobs without steps from older versions have none). */
const jobTokens = (job: PasswordJob, pendingOnly = false) =>
  (job.separate ?? []).filter((part) => !(pendingOnly && part.dispatched)).flatMap((part) => (part.shares ?? []).map((s) => s.token));

/**
 * Links of the owner whose mail CloudShare has not seen sent yet (password not sent): token → when they are revoked if
 * the mail is still not sent (ms), or null if they are not revoked automatically. For "Verlauf".
 * Links "Ohne Kennwort" are not tracked: they may well have gone out from a client without CloudShare.
 */
export function unsentShares(owner: string): Map<string, number | null> {
  const unsent = new Map<string, number | null>();
  for (const job of jobs.values()) {
    if (job.owner !== owner || job.dispatched || job.noPassword || job.armed) continue;
    for (const token of jobTokens(job, true)) unsent.set(token, neverSent(job) ? job.expiresAt : null);
  }
  return unsent;
}

type UnsentHandler = (links: UnsentLinks, log: Pick<FastifyBaseLogger, "info" | "warn">) => Promise<void>;
let unsentHandler: UnsentHandler | undefined;
/** What to do with the links of a job that expired without its mail ever being sent (index.ts: revoke them). */
export function onUnsentExpired(handler: UnsentHandler | undefined) {
  unsentHandler = handler;
}

export async function createJob(
  owner: string,
  ownerUpn: string,
  fileName: string,
  sendUrl: string,
  maxAccessCount?: number,
  sendId?: string,
): Promise<string> {
  const id = randomUUID();
  jobs.set(id, {
    owner,
    ownerUpn,
    fileNames: [fileName],
    sendUrl,
    maxAccessCount,
    sendId,
    dispatched: false,
    expiresAt: Date.now() + JOB_TTL,
    armedOnce: false,
  });
  return id;
}

export async function addFileToJob(id: string, fileName: string): Promise<void> {
  const job = jobs.get(id)!;
  job.fileNames.push(fileName);
  touch(job);
  jobs.save(id);
}

/** First step of a mail with one password per step (see SeparatePart). */
export async function createSeparateJob(owner: string, ownerUpn: string, part: SeparatePart): Promise<string> {
  const id = randomUUID();
  jobs.set(id, {
    owner,
    ownerUpn,
    fileNames: [...part.fileNames],
    separate: [part],
    sendUrl: part.sendUrl,
    maxAccessCount: part.maxAccessCount,
    dispatched: false,
    expiresAt: Date.now() + JOB_TTL,
    armedOnce: false,
  });
  return id;
}

/** Job for links "Ohne Kennwort" that only exists for the download confirmation (see PasswordJob.noPassword). */
export async function createNoticeJob(owner: string, ownerUpn: string, share: StepShare): Promise<string> {
  const id = randomUUID();
  jobs.set(id, {
    owner,
    ownerUpn,
    fileNames: [share.name],
    sendUrl: "",
    noPassword: true,
    noticeShares: [share],
    dispatched: false,
    expiresAt: Date.now() + JOB_TTL,
  });
  return id;
}

export async function addNoticeShare(id: string, share: StepShare): Promise<void> {
  const job = jobs.get(id)!;
  job.fileNames.push(share.name);
  (job.noticeShares ??= []).push(share);
  touch(job);
  jobs.save(id);
}

/** The password goes by SMS: the Sends of steps not sent yet only hold it until then – keep them to `expiresAt`. */
export async function setPartsExpiry(id: string, expiresAt: number): Promise<void> {
  const job = jobs.get(id);
  if (!job?.separate) return;
  for (const part of job.separate) if (!part.dispatched && part.sendId) part.sendExpiresAt = expiresAt;
  jobs.save(id);
}

/** Further step with its own password and password mail. */
export async function addSeparatePart(id: string, part: SeparatePart): Promise<void> {
  const job = jobs.get(id)!;
  job.fileNames.push(...part.fileNames);
  (job.separate ??= []).push(part);
  touch(job);
  jobs.save(id);
}

/** The part of a step, if the step already created one (further files of the same click). */
export const findPart = (id: string, step: string) => jobs.get(id)?.separate?.find((p) => p.step === step);

/**
 * Further link of the same step: same password, same Send. Its way ("Kennwort senden an") joins the step's ways if it
 * is a new one – the password then goes out that way too.
 */
export async function addFileToPart(id: string, step: string, fileName: string, share?: StepShare, delivery?: Delivery): Promise<void> {
  const job = jobs.get(id)!;
  job.fileNames.push(fileName);
  const part = findPart(id, step)!;
  part.fileNames.push(fileName);
  if (share) (part.shares ??= []).push(share);
  if (delivery) {
    const ways = part.deliveries ?? partDeliveries(job, part);
    if (!ways.some((d) => deliveryKey(d) === deliveryKey(delivery))) part.deliveries = [...ways, delivery];
  }
  touch(job);
  jobs.save(id);
}

